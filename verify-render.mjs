import assert from 'node:assert/strict';
import sharp from 'sharp';
import {mathParts,discordPayloads} from './math.mjs';
import {discordMessages,tableMessages,displayWidth} from './format.mjs';
const formula=String.raw`\[\frac{-b\pm\sqrt{b^2-4ac}}{2a}\]`;
const code='```tex\n'+formula+'\n```\n`$x$`\n价格 $20 和 $30';
assert.deepEqual(mathParts(code),[{text:code}]);
const payloads=await discordPayloads('正文\n'+formula+'\n后文');
assert.equal(payloads[0].content,'正文\n');assert.equal(payloads.at(-1).content,'\n后文');
assert.equal((await sharp(payloads[1].files[0].attachment).metadata()).format,'png');
assert.equal(mathParts(String.raw`\(x^2\) 和 $y^3$`).filter(p=>p.tex).length,2);
assert.ok((await discordPayloads(String.raw`\[\UnknownCommand{x}\]`))[0].content.includes('UnknownCommand'));
assert.ok((await discordPayloads(formula,async()=>{throw Error('fixture');}))[0].content.includes('frac'));
const table='| 项目 | 数量 |\n|---|---|\n| 测试 A | 10 |\n| 测试 B | 20 |';
assert.deepEqual((await discordPayloads(table)).map(p=>p.content),discordMessages(table));
const rows=Array.from({length:200},(_,i)=>['row-'+i,'说明文字😀 '+i]);
const messages=tableMessages(['编号','内容'],rows);
assert.ok(messages.every(s=>s.startsWith('```text\n')&&s.endsWith('\n```')&&s.length<=1800));
for(const row of rows)for(const cell of row)assert.ok(messages.join('\n').includes(cell));
assert.equal(displayWidth('中文abc'),7);assert.equal(displayWidth('e\u0301'),1);
console.log('PASS: math PNG, fallback, code/currency, ordered prose, table regression and 200 complete rows.');
